/* Employer dashboard – Challans & Payments > F-4 return (monthly statement of contributions, printable). */
import { ActionButton, BackIcon, PrintIcon } from '@/components/ui/ActionButton';
import type { ViewProps } from '@/types/view';
import type { DocumentsView } from '../../logic/documents';
import { DOC_LABEL, DOC_VALUE, DocumentFooter, DocumentHeader, DocumentSheet, DocumentTitleRow } from './documents/DocumentParts';
import { WorkerScheduleTable } from './documents/WorkerScheduleTable';

export function F4FormSection({ v }: ViewProps) {
  const { f4Form: f, company } = v as DocumentsView;

  if (!f.found) {
    return (
      <div className="mt-4 rounded-[10px] border border-solid border-essi-line bg-white p-5 text-[14px] text-ink-muted">
        No F-4 return yet. It is available after your first contribution is paid.
        <div className="mt-4">
          <ActionButton onClick={v.goHome} icon={<BackIcon />}>
            Back to Dashboard
          </ActionButton>
        </div>
      </div>
    );
  }

  const employer: [string, string][] = [
    ['Name of Establishment', company.name.toUpperCase()],
    ['Employer Identification No.', company.empNo],
    ['Industry Classification', company.industry || '-'],
    ['Address', company.address],
    ['NTN', company.ntn],
    ['Directorate', company.directorate],
    ['Contribution month', f.month],
    ['Receipt No.', f.receiptNo],
  ];

  return (
    <div className="mt-4">
      <DocumentSheet>
        <DocumentHeader directorate={company.directorate} />
        <DocumentTitleRow
          left={
            <>
              Form: <b>F-4</b>
            </>
          }
          title="RETURN OF CONTRIBUTIONS – STATEMENT OF WORKERS AND WAGES"
          right={
            <>
              Month: <b>{f.month}</b>
            </>
          }
        />

        <table className="w-full border-collapse">
          <tbody>
            {employer.map(([label, value]) => (
              <tr key={label}>
                <td className={DOC_LABEL}>{label}</td>
                <td className={DOC_VALUE}>{value}</td>
              </tr>
            ))}
          </tbody>
        </table>

        <WorkerScheduleTable rows={f.rows} moreWorkers={f.moreWorkers} />

        <div className="mt-3.5 overflow-x-auto">
          <table className="w-full border-collapse">
            <tbody>
              <tr>
                <td className={DOC_LABEL}>Total number of workers</td>
                <td className={DOC_VALUE}>{f.workers}</td>
              </tr>
              <tr>
                <td className={DOC_LABEL}>Contribution paid under section 20(1)</td>
                <td className={DOC_VALUE}>Rs. {f.contribution}</td>
              </tr>
              <tr>
                <td className={DOC_LABEL}>Service charges</td>
                <td className={DOC_VALUE}>Rs. {f.serviceCharges}</td>
              </tr>
              <tr>
                <td className={DOC_LABEL}>Total paid</td>
                <td className={DOC_VALUE}>
                  <b>Rs. {f.total}</b> (Rupees {f.totalWords} ONLY)
                </td>
              </tr>
            </tbody>
          </table>
        </div>

        <div className="mt-10 flex flex-wrap justify-between gap-6 text-[14px]">
          <div className="min-w-[220px] border-0 border-t border-solid border-ink-print pt-1.5 text-center">Signature of Employer / Authorized Person</div>
          <div className="min-w-[220px] border-0 border-t border-solid border-ink-print pt-1.5 text-center">Company Stamp</div>
        </div>

        <DocumentFooter note="I certify that the particulars given in this return are correct and complete. This return is generated by the portal from the contribution submitted for the month above." />
        <div className="mt-3 font-arial text-[12px] text-[#555]">Sample F-4 return with dummy values; only the first workers of the schedule are listed.</div>
      </DocumentSheet>

      <div className="mt-4 flex flex-wrap gap-2.5">
        <ActionButton variant="primary" onClick={v.printDoc} icon={<PrintIcon />}>
          Print F-4
        </ActionButton>
        <ActionButton onClick={v.goF4}>F-4 List</ActionButton>
        <ActionButton onClick={v.goHome} icon={<BackIcon />}>
          Back to Dashboard
        </ActionButton>
      </div>
    </div>
  );
}
