/* Employer dashboard – Challans & Payments > Payment Receipt (printable). */
import { ActionButton, BackIcon, PrintIcon } from '@/components/ui/ActionButton';
import type { ViewProps } from '@/types/view';
import type { DocumentsView } from '../../logic/documents';
import { DOC_LABEL, DOC_TD, DOC_TH, DOC_VALUE, DocumentFooter, DocumentHeader, DocumentSheet, DocumentTitleRow, PaidStamp } from './documents/DocumentParts';

export function ReceiptSection({ v }: ViewProps) {
  const { receipt: r, company } = v as DocumentsView;

  if (!r.found) {
    return (
      <div className="mt-4 rounded-[10px] border border-solid border-essi-line bg-white p-5 text-[14px] text-ink-muted">
        No payments yet. A receipt is available after you pay a challan.
        <div className="mt-4">
          <ActionButton onClick={v.goHome} icon={<BackIcon />}>
            Back to Dashboard
          </ActionButton>
        </div>
      </div>
    );
  }

  const details: [string, string][] = [
    ['Payment status', r.isPaid ? 'PAID' : 'UNPAID'],
    ['Payment channel', r.channel],
    ['1Bill Payment No.', r.billNo],
    ['Transaction / Reference ID', r.transactionId],
    ['Paid on', r.paidOn],
    ['Due date', r.dueDate],
    ['Amount paid', 'Rs. ' + r.total + ' (Rupees ' + r.totalWords + ' ONLY)'],
  ];

  return (
    <div className="mt-4">
      {r.isPaid ? (
        <div className="flex items-center gap-2.5 rounded-lg border border-solid border-[#9fd3ae] bg-[#e8f6ec] px-4 py-3 text-[14px] text-essi-dark">
          <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="#067a35" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" className="flex-none">
            <path d="M5 12l5 5 9-10" />
          </svg>
          <span>
            <b>Payment received.</b> Challan {r.challanNo} for {r.month} has been paid. Print or save this receipt for your records.
          </span>
        </div>
      ) : null}

      <DocumentSheet>
        {r.isPaid ? <PaidStamp /> : null}
        <DocumentHeader directorate={company.directorate} />
        <DocumentTitleRow
          left={
            <>
              Date: <b>{r.paidOn}</b>
            </>
          }
          title="PAYMENT RECEIPT OF SOCIAL SECURITY CONTRIBUTION"
          right={
            <>
              Receipt No. <b>{r.receiptNo}</b>
            </>
          }
        />

        <div className="overflow-x-auto">
          <table className="w-full min-w-[820px] border-collapse">
            <tbody>
              <tr>
                {['Month for which Contribution paid', 'Challan No.', 'Employer Identification No.', 'Number of Workers', 'Name of Establishment', 'Contribution paid under section 20(1)', 'Service Charges', 'Total Paid'].map((h) => (
                  <th key={h} className={DOC_TH}>
                    {h}
                  </th>
                ))}
              </tr>
              <tr>
                <td className={DOC_TD}>{r.month}</td>
                <td className={DOC_TD}>{r.challanNo}</td>
                <td className={DOC_TD}>{company.empNo}</td>
                <td className={DOC_TD}>{r.workers}</td>
                <td className={DOC_TD}>{company.name.toUpperCase()}</td>
                <td className={DOC_TD}>Rs. {r.contribution}</td>
                <td className={DOC_TD}>Rs. {r.serviceCharges}</td>
                <td className={DOC_TD}>Rs. {r.total}</td>
              </tr>
            </tbody>
          </table>
        </div>

        <div className="mt-3.5 overflow-x-auto">
          <table className="w-full border-collapse">
            <tbody>
              {details.map(([label, value]) => (
                <tr key={label}>
                  <td className={DOC_LABEL}>{label}</td>
                  <td className={DOC_VALUE}>{label === 'Payment status' ? <b className={r.isPaid ? 'text-essi-paid' : 'text-warning'}>{value}</b> : value}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        <DocumentFooter note="This receipt is generated by the portal once 1LINK confirms the payment. Keep it with your records together with the bank or app payment slip. Officers of the Institution may inspect employers’ records under section 23." />
      </DocumentSheet>

      <div className="mt-4 flex flex-wrap gap-2.5">
        <ActionButton variant="primary" onClick={v.printDoc} icon={<PrintIcon />}>
          Print Receipt
        </ActionButton>
        <ActionButton onClick={v.goHist}>Payment History</ActionButton>
        <ActionButton onClick={v.goHome} icon={<BackIcon />}>
          Back to Dashboard
        </ActionButton>
      </div>
    </div>
  );
}
